bool font_cov_has(uint32_t cp)
{
    int lo = 0, hi = (int)(sizeof COV / sizeof COV[0]) - 1;
    while (lo <= hi) {
        int m = (lo + hi) / 2;
        if (cp < COV[m][0]) hi = m - 1;
        else if (cp > COV[m][1]) lo = m + 1;
        else return true;
    }
    return false;
}
